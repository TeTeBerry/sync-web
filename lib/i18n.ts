export const LOCALES = ['zh', 'en'] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = 'en';

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

export function normalizeLocale(value?: string): Locale {
  return value && isLocale(value) ? value : DEFAULT_LOCALE;
}

/** loading.tsx does not receive route params — resolve locale from params, proxy header, or default. */
export async function resolveLoadingLocale(params?: Promise<{ locale?: string }>): Promise<Locale> {
  if (params) {
    const resolved = await params;
    if (resolved?.locale && isLocale(resolved.locale)) {
      return resolved.locale;
    }
  }

  const { headers } = await import('next/headers');
  const headerLocale = (await headers()).get('x-sync-locale');
  return normalizeLocale(headerLocale ?? undefined);
}

export function localizedPath(locale: Locale, path = ''): string {
  const cleanPath = path.startsWith('/') ? path : `/${path}`;
  return `/${locale}${cleanPath === '/' ? '' : cleanPath}`;
}

export function alternateLanguages(path = ''): Record<string, string> {
  return {
    'x-default': localizedPath(DEFAULT_LOCALE, path),
    'zh-CN': localizedPath('zh', path),
    en: localizedPath('en', path),
  };
}

